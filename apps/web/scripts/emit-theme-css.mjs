// Generates app/theme.css from @salamstay/design-tokens cssVariables.
// Single source of truth: the tokens package. Never hand-edit theme.css.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { cssVariables } from "@salamstay/design-tokens/tailwind-preset";

const toBlock = (selector, vars) =>
  `${selector} {\n${Object.entries(vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n")}\n}\n`;

const css = `/* GENERATED by scripts/emit-theme-css.mjs — do not edit. */\n${toBlock(
  ":root",
  cssVariables.light,
)}\n${toBlock(".dark", cssVariables.dark)}`;

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "app", "theme.css");
writeFileSync(out, css);
console.log(`theme.css written (${Object.keys(cssVariables.light).length} vars/theme)`);
